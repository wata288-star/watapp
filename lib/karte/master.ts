export function itemsForMachine(machineType?: string): MasterItem[] {
  const typed = MACHINE_TYPES.includes(machineType as MachineType)
    ? TYPE_ITEMS.filter((i) => i.machineType === machineType)
    : [];
  return [...COMMON_ITEMS, ...typed];
}

// ---------------- 査定準備状況の算定 ----------------

export interface ItemStatus {
  item: MasterItem;
  status: "ok" | "stale" | "missing"; // 12ヶ月以内の記録あり / 古い記録のみ / 記録なし
  lastAt: string | null;
}

export interface ReadinessResult {
  items: ItemStatus[];
  highTotal: number;
  highOk: number;
  missingHigh: ItemStatus[]; // 未記録・要更新の高インパクト項目
}

function fieldSatisfied(machine: Machine, field: NonNullable<MasterItem["field"]>): boolean {
  switch (field) {
    case "ident":
      return Boolean(machine.maker && machine.model && machine.serialNo);
    case "year":
      return Boolean(machine.yearMade);
    case "purchase":
      return Boolean(machine.purchasedAt);
    case "docs":
      return machine.docs.length > 0;
    case "spec":
      return Boolean(machine.ratedPower);
  }
}

export function assessReadiness(
  machine: Machine,
  records: MaintRecord[],
  asOf: string,
): ReadinessResult {
  const items = itemsForMachine(machine.machineType);
  const twelveMonthsAgo = `${Number(asOf.slice(0, 4)) - 1}${asOf.slice(4)}`;

  const statuses: ItemStatus[] = items.map((item) => {
    if (item.field) {
      const ok = fieldSatisfied(machine, item.field);
      return { item, status: ok ? "ok" : "missing", lastAt: ok ? machine.registeredAt : null };
    }
    let lastAt: string | null = null;
    if (item.keywords) {
      for (const r of records) {
        const text = r.title + " " + r.memo;
        if (item.keywords.some((k) => text.includes(k))) {
          if (!lastAt || r.workDate > lastAt) lastAt = r.workDate;
        }
      }
    }
    // 「定期点検の実施記録」は点検種別そのものでも充足
    if (item.id === "c14" && !lastAt) {
      const insp = records.filter((r) => r.type === "inspection" || r.type === "legal");
      if (insp.length > 0) lastAt = insp[0].workDate;
    }
    if (!lastAt) return { item, status: "missing", lastAt: null };
    // 「都度」項目は発生時のみのため、記録があれば充足とみなす
    const isPeriodic = item.timing.includes("定期");
    const status = !isPeriodic || lastAt >= twelveMonthsAgo ? "ok" : "stale";
    return { item, status, lastAt };
  });

  const high = statuses.filter((s) => s.item.impact === "高");
  // 「都度」の履歴系(修理・交換等)は発生がなければ未記録でも減点しない
  const highRelevant = high.filter(
    (s) => !(s.item.timing === "都度" && s.status === "missing"),
  );
  const highOk = highRelevant.filter((s) => s.status === "ok").length;
  const missingHigh = high.filter((s) => s.status !== "ok" && s.item.timing !== "都度");

  return {
    items: statuses,
    highTotal: highRelevant.length,
    highOk,
    missingHigh,
  };
}
